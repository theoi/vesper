export function isRoleId(x: unknown): x is RoleId {
  return typeof x === 'string' && Object.hasOwn(ROLES, x);
}

export function isRandomSlot(x: unknown): x is RandomSlot {
  return typeof x === 'string' && Object.hasOwn(RANDOM_SLOT_ROLES, x);
}

export function slotName(slot: string): string {
  if (isRoleId(slot)) return ROLES[slot].name;
  if (isRandomSlot(slot)) return RANDOM_SLOT_NAMES[slot];
  return slot;
}
